// Rasterises Natural Earth land polygons (via the world-atlas npm package)
// into the compact run-length land mask used by the "Earth Remixed" map.
//
//   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0
//   node tools/build-earth-mask.mjs > src/map/earthMask.js
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { feature } = require('topojson-client');
const src = process.argv[2] || require.resolve('world-atlas/land-50m.json');
const topo = JSON.parse(readFileSync(src, 'utf8'));
const land = feature(topo, topo.objects.land);

const W = 1024, H = 512, LAT_TOP = 84, LAT_BOTTOM = -62;
const rings = [];
for (const f of land.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p of polys) for (const r of p) {
    // Unwrap longitudes so rings that cross the antimeridian stay continuous.
    const u = [[r[0][0], r[0][1]]];
    for (let i = 1; i < r.length; i++) {
      let lon = r[i][0];
      const prev = u[i - 1][0];
      while (lon - prev > 180) lon -= 360;
      while (prev - lon > 180) lon += 360;
      u.push([lon, r[i][1]]);
    }
    rings.push(u);
  }
}

const mask = new Uint8Array(W * H);
// Fill each ring on its own with even-odd XOR, so one awkward ring can't
// corrupt a whole scanline. Holes cancel out because they are XORed too.
for (const r of rings) {
  let minLat = Infinity, maxLat = -Infinity;
  for (const [, la] of r) { minLat = Math.min(minLat, la); maxLat = Math.max(maxLat, la); }
  const y0 = Math.max(0, Math.floor(((LAT_TOP - maxLat) / (LAT_TOP - LAT_BOTTOM)) * H) - 1);
  const y1 = Math.min(H - 1, Math.ceil(((LAT_TOP - minLat) / (LAT_TOP - LAT_BOTTOM)) * H) + 1);
  for (let y = y0; y <= y1; y++) {
    const lat = LAT_TOP - ((y + 0.5) / H) * (LAT_TOP - LAT_BOTTOM);
    const xs = [];
    for (let i = 0; i < r.length - 1; i++) {
      const [ax, ay] = r[i], [bx, by] = r[i + 1];
      if ((ay <= lat && by > lat) || (by <= lat && ay > lat)) xs.push(ax + ((lat - ay) / (by - ay)) * (bx - ax));
    }
    if (xs.length % 2) continue;
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const a = Math.ceil(((xs[k] + 180) / 360) * W - 0.5);
      const b = Math.floor(((xs[k + 1] + 180) / 360) * W - 0.5);
      for (let x = a; x <= b; x++) mask[y * W + (((x % W) + W) % W)] ^= 1;
    }
  }
}

// Run-length encode: alternating water/land run lengths (base 36), rows separated by commas.
const rows = [];
for (let y = 0; y < H; y++) {
  const runs = [];
  let cur = 0, n = 0;
  for (let x = 0; x < W; x++) {
    const v = mask[y * W + x];
    if (v === cur) n++;
    else { runs.push(n.toString(36)); cur = v; n = 1; }
  }
  runs.push(n.toString(36));
  rows.push(runs.join('.'));
}

console.log(`// Generated by tools/build-earth-mask.mjs from Natural Earth land polygons
// (public domain) via the world-atlas package. ${W}x${H} equirectangular mask.
export const EARTH_W = ${W};
export const EARTH_H = ${H};
export const LAT_TOP = ${LAT_TOP};
export const LAT_BOTTOM = ${LAT_BOTTOM};
export const EARTH_RLE = ${JSON.stringify(rows.join(','))};`);
